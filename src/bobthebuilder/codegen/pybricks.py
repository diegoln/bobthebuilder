"""Generate a Pybricks (EV3 MicroPython) program from a validated spec.

The point: ports, wheel diameter, axle track and gear ratios come from the
same ResolvedSpec that produced the build, so code and hardware can't drift.
"""

from __future__ import annotations

from bobthebuilder.modules.base import DeviceKind
from bobthebuilder.validators.base import ResolvedSpec

_SENSOR_CLASS = {
    DeviceKind.SENSOR_COLOR: "ColorSensor",
    DeviceKind.SENSOR_TOUCH: "TouchSensor",
    DeviceKind.SENSOR_IR: "InfraredSensor",
    DeviceKind.SENSOR_ULTRASONIC: "UltrasonicSensor",
    DeviceKind.SENSOR_GYRO: "GyroSensor",
}


def _port_expr(port: str) -> str:
    return f"Port.{port}"


def generate(rs: ResolvedSpec) -> str:
    spec = rs.spec
    lines = [
        "#!/usr/bin/env pybricks-micropython",
        f'"""{spec.name} — generated by bobthebuilder for task: {spec.task}"""',
        "from pybricks.hubs import EV3Brick",
        "from pybricks.ev3devices import (Motor, TouchSensor, ColorSensor,",
        "                                 InfraredSensor, UltrasonicSensor, GyroSensor)",
        "from pybricks.parameters import Port, Direction",
        "from pybricks.robotics import DriveBase",
        "from pybricks.tools import wait",
        "",
        "ev3 = EV3Brick()",
        "",
    ]
    drive_inst = None
    for inst in spec.modules:
        r = rs.resolved.get(inst.id)
        if r is None:
            continue
        lines.append(f"# --- {inst.id} ({r.module_id}) ---")
        for d in r.devices:
            port = inst.ports[d.role].value
            var = f"{inst.id}_{d.role}"
            if d.kind.is_motor:
                lines.append(f"{var} = Motor({_port_expr(port)})")
            else:
                lines.append(f"{var} = {_SENSOR_CLASS[d.kind]}({_port_expr(port)})")
        for k, v in r.geometry.items():
            lines.append(f"{inst.id.upper()}_{k.upper()} = {v!r}")
        if r.module_id.startswith("drivebase"):
            drive_inst = inst.id
        lines.append("")

    if drive_inst:
        ratio = rs.resolved[drive_inst].geometry["drive_gear_ratio"]
        lines += [
            "# DriveBase uses wheel geometry from the design. With a gear reduction the",
            "# motor turns `ratio` times per wheel turn, so scale the wheel diameter down.",
            f"robot = DriveBase({drive_inst}_left_motor, {drive_inst}_right_motor,",
            f"                  wheel_diameter={drive_inst.upper()}_WHEEL_DIAMETER_MM / {ratio!r},",
            f"                  axle_track={drive_inst.upper()}_AXLE_TRACK_MM)",
            "",
        ]

    lines += [
        "",
        "def main():",
        "    ev3.speaker.beep()",
        "    # TODO: behaviour for the task goes here.",
    ]
    if drive_inst:
        lines.append("    robot.straight(200)")
    lines += ["", "", 'if __name__ == "__main__":', "    main()", ""]
    return "\n".join(lines)
